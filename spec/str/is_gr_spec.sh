#!/bin/sh
# shellcheck disable=SC3003 # 高位バイトにはPOSIX.1-2024のドル単一引用符を使用する。

eval "$(shellspec - -c) exit 1"

Describe 'sx_str_is_gr / __sx_str_is_gr'
  sxtest_load ./build/modules/sx_str_is_gr.sh

  Context 'GR領域の全96値'
    Parameters:matrix
      sx_str_is_gr __sx_str_is_gr
      $'\240' $'\241' $'\242' $'\243' $'\244' $'\245' $'\246' $'\247' $'\250' $'\251' $'\252' $'\253' $'\254' $'\255' $'\256' $'\257' $'\260' $'\261' $'\262' $'\263' $'\264' $'\265' $'\266' $'\267' $'\270' $'\271' $'\272' $'\273' $'\274' $'\275' $'\276' $'\277' $'\300' $'\301' $'\302' $'\303' $'\304' $'\305' $'\306' $'\307' $'\310' $'\311' $'\312' $'\313' $'\314' $'\315' $'\316' $'\317' $'\320' $'\321' $'\322' $'\323' $'\324' $'\325' $'\326' $'\327' $'\330' $'\331' $'\332' $'\333' $'\334' $'\335' $'\336' $'\337' $'\340' $'\341' $'\342' $'\343' $'\344' $'\345' $'\346' $'\347' $'\350' $'\351' $'\352' $'\353' $'\354' $'\355' $'\356' $'\357' $'\360' $'\361' $'\362' $'\363' $'\364' $'\365' $'\366' $'\367' $'\370' $'\371' $'\372' $'\373' $'\374' $'\375' $'\376' $'\377'
    End

    It '各値を受理すること'
      When call "$1" "$2"
      The status should equal 0
    End
  End

  Context 'GR領域以外の入力'
    Parameters:matrix
      sx_str_is_gr __sx_str_is_gr
      '' 'a' 'Z' '0' ' ' '~' '*' '?' '[' ']' '-' '^' '\' "'" '"' '$' '`' '\xA0' $'\001' $'\t' $'\n' $'\037' $'\177' $'\200' $'\237'
    End

    It '不一致として1を返すこと'
      When call "$1" "$2"
      The status should equal 1
    End
  End

  Context '引数列と境界条件'
    Parameters
      sx_str_is_gr
      __sx_str_is_gr
    End

    It '全96値を連結した文字列を受理すること'
      When call "$1" $'\240\241\242\243\244\245\246\247\250\251\252\253\254\255\256\257\260\261\262\263\264\265\266\267\270\271\272\273\274\275\276\277\300\301\302\303\304\305\306\307\310\311\312\313\314\315\316\317\320\321\322\323\324\325\326\327\330\331\332\333\334\335\336\337\340\341\342\343\344\345\346\347\350\351\352\353\354\355\356\357\360\361\362\363\364\365\366\367\370\371\372\373\374\375\376\377'
      The status should equal 0
    End

    It 'GR領域の複数の値と複数の引数を受理すること'
      When call "$1" $'\240\377' $'\255\300\376'
      The status should equal 0
    End

    It '引数がない場合、0を返すこと'
      When call "$1"
      The status should equal 0
    End

    It '先頭の引数が空文字列の場合、1を返すこと'
      When call "$1" '' $'\240' $'\377'
      The status should equal 1
    End

    It '途中の引数が空文字列の場合、1を返すこと'
      When call "$1" $'\240' '' $'\377'
      The status should equal 1
    End

    It '最後の引数が空文字列の場合、1を返すこと'
      When call "$1" $'\240' $'\377' ''
      The status should equal 1
    End

    It '先頭に範囲外のバイトが混在する場合、1を返すこと'
      When call "$1" $'\237\240' $'\377'
      The status should equal 1
    End

    It '途中に範囲外のバイトが混在する場合、1を返すこと'
      When call "$1" $'\240\237\377'
      The status should equal 1
    End

    It '末尾に範囲外のバイトが混在する場合、1を返すこと'
      When call "$1" $'\240' $'\377\237'
      The status should equal 1
    End

    It '途中の引数が範囲外の場合、1を返すこと'
      When call "$1" $'\240' 'a' $'\377'
      The status should equal 1
    End

    It '長いGR文字列を受理すること'
      long_gr=$'\240\377'
      for step in 1 2 3 4 5 6 7 8 9; do
        long_gr="${long_gr}${long_gr}"
      done
      When call "$1" "${long_gr}"
      The status should equal 0
    End
  End
End
